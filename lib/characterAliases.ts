// Whether a canonical character name matches a typed query, either directly
// or through one of its known aliases (e.g. typing "Usui" matches canonical
// name "Masumi Usui").
export function matchesCharacterName(name: string, query: string): boolean {
  if (!query) return true;
  const q = query.toLowerCase();
  if (name.toLowerCase().includes(q)) return true;
  const aliases = CHARACTER_ALIASES[name];
  return aliases ? aliases.some((a) => a.toLowerCase().includes(q)) : false;
}
